// ── Validaciones previas a la inserción ─────────────────────
const TIPOS_VALIDOS = [
  'hotel', 'restaurant', 'bar', 'escenario_deportivo', 'parque', 'naturaleza',
  'cultura', 'artesania', 'playa', 'ruta', 'gastronomia', 'compras', 'servicio',
];
const MUNICIPIOS_VALIDOS = ['sincelejo', 'santiago_de_tolu', 'covenas', 'sampues'];

function validateData() {
  const porMunicipio = {};
  const porTipo = {};
  const rewardsPorMunicipio = {};

  for (const p of places) {
    if (!TIPOS_VALIDOS.includes(p.tipo)) {
      throw new Error(`Tipo inválido: "${p.tipo}" en "${p.name}"`);
    }
    if (!MUNICIPIOS_VALIDOS.includes(p.municipio)) {
      throw new Error(`Municipio inválido: "${p.municipio}" en "${p.name}"`);
    }
    porMunicipio[p.municipio] = (porMunicipio[p.municipio] || 0) + 1;
    porTipo[p.tipo] = (porTipo[p.tipo] || 0) + 1;
    if (p.has_reward) {
      rewardsPorMunicipio[p.municipio] = (rewardsPorMunicipio[p.municipio] || 0) + 1;
    }
  }

  console.log('\n📊 Conteo por municipio:');
  for (const m of MUNICIPIOS_VALIDOS) {
    console.log(`   ${m}: ${porMunicipio[m] || 0}`);
  }

  console.log('\n🎁 Lugares con recompensa por municipio:');
  for (const m of MUNICIPIOS_VALIDOS) {
    const count = rewardsPorMunicipio[m] || 0;
    const ok = count >= 2 ? '✅' : '❌';
    console.log(`   ${ok} ${m}: ${count}`);
    if (count < 2) throw new Error(`${m} tiene menos de 2 lugares con recompensa`);
  }

  const total = places.length;
  if (total !== 55) throw new Error(`Total esperado 55, encontrado ${total}`);

  console.log(`\n✅ Validación OK — ${total} lugares, tipos y municipios correctos.\n`);
  return { porMunicipio, porTipo };
}

async function main() {
  console.log('🌴 Iniciando seed de lugares en Sucre...');
  console.log(`📍 Total a insertar: ${places.length} lugares`);

  validateData();

  let inserted = 0;
  let errors = 0;

  for (const place of places) {
    try {
      await prisma.$executeRaw`
        INSERT INTO places (
          name, tipo, municipio, latitud, longitud, lugar, description,
          address, phone, rating, price_range, amenities,
          has_reward, reward_name, reward_description, reward_icon, reward_stock,
          is_active, owner_id, categoria, created_at, updated_at
        ) VALUES (
          ${place.name}, ${place.tipo}, ${place.municipio},
          ${place.latitud}, ${place.longitud}, ${place.lugar},
          ${place.description}, ${place.address}, ${place.phone},
          ${place.rating}, ${place.price_range}, ${place.amenities},
          ${place.has_reward}, ${place.reward_name ?? null},
          ${place.reward_description ?? null}, ${place.reward_icon ?? null},
          ${place.reward_stock ?? null}, ${place.is_active},
          ${place.owner_id ?? null}, ${place.categoria ?? null},
          NOW(), NOW()
        )
      `;
      inserted++;
      console.log(`  ✅ [${place.municipio}] ${place.name}`);
    } catch (err) {
      errors++;
      console.error(`  ❌ Error en "${place.name}":`, err.message);
    }
  }

  console.log('\n═══════════════════════════════════');
  console.log(`✅ Insertados: ${inserted}`);
  console.log(`❌ Errores:    ${errors}`);
  console.log('═══════════════════════════════════');
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
